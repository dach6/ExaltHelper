public static string MarkDungeon(string name) => Marks.TryGetValue(name ?? "", out string dungeon) ? dungeon : null;
public static string[] Dungeons(MissionObjective objective) {
    if (objective.Type == 3 || objective.Type == 14) return new[] { objective.Target };
    if (objective.Type == 1) {
        string target = objective.Target;
        if (Bosses.TryGetValue(target, out string dungeon)) return new[] { dungeon };
        int space = target.IndexOf(' ');
        if (space > 0 && target.Substring(0, space).All(c => char.IsLower(c) || char.IsDigit(c)) && Bosses.TryGetValue(target.Substring(space + 1), out dungeon)) return new[] { dungeon };
    }
    if (objective.Type == 4 || objective.Type == 12) {
        string[] bounds = objective.Target.Split('-');
        if (double.TryParse(bounds[0], System.Globalization.NumberStyles.Float, System.Globalization.CultureInfo.InvariantCulture, out double minimum)) {
            double maximum = minimum;
            if (bounds.Length > 1) double.TryParse(bounds[1], System.Globalization.NumberStyles.Float, System.Globalization.CultureInfo.InvariantCulture, out maximum);
            return Difficulty.Where(p => p.Value >= minimum && p.Value <= maximum).OrderBy(p => p.Value).Select(p => p.Key).ToArray();
        }
    }
    return Array.Empty<string>();
}
public static string Location(string dungeon) => Sources.TryGetValue(dungeon ?? "", out string locations) ? locations : "Enter " + dungeon + ".";
